2. **本を閉じて、要点を3つ書き出す**(思い出す練習)
3. **自分の言葉で、例を1つ考える**(精緻化)
4. **テキストに戻って、抜けていたところを確かめる**
5. **翌日と数日後に、問題集で同じ範囲を解く**(間隔をあけた復習)
